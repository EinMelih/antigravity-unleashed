    async def cancel_cascade_invocation(self, cascade_id: str) -> Dict[str, Any]:
        """Stop an active generation immediately (`CancelCascadeInvocation`)."""
        return await self.call_unary(
            "CancelCascadeInvocation", {"cascadeId": cascade_id}, timeout=5.0
        )

    async def get_trajectory_steps(
        self, cascade_id: str, step_offset: int = 0
    ) -> List[Dict[str, Any]]:
        """Read trajectory steps for `cascade_id` via `GetCascadeTrajectorySteps`."""
        try:
            resp = await self.call_unary(
                "GetCascadeTrajectorySteps",
                {"cascadeId": cascade_id, "stepOffset": max(0, int(step_offset))},
                timeout=10.0,
            )
            steps = resp.get("steps")
            if isinstance(steps, list):
                return steps
        except Exception:
            pass
        try:
            resp = await self.call_unary(
                "GetCascadeTrajectory", {"cascadeId": cascade_id}, timeout=10.0
            )
            traj = resp.get("trajectory") or {}
            steps = traj.get("steps") or []
            return steps[step_offset:] if isinstance(steps, list) else []
        except Exception:
            return []

    async def get_generator_metadata(self, cascade_id: str) -> Dict[str, Any]:
        """Fetch exact token & context window metadata (`GetCascadeTrajectoryGeneratorMetadata`)."""
        try:
            return await self.call_unary(
                "GetCascadeTrajectoryGeneratorMetadata",
                {"cascadeId": cascade_id},
                timeout=10.0,
            )
        except Exception:
            return {}

    async def auto_approve_waiting_steps(
        self, cascade_id: str, steps: List[Dict[str, Any]], step_offset: int = 0
    ) -> int:
        """Detect any step in `WAITING` status (9) and immediately approve it via `HandleCascadeUserInteraction`."""
        approved = 0
        for idx, step in enumerate(steps):
            if not isinstance(step, dict):
                continue
            status = step.get("status")
            is_waiting = status in (
                9,
                "CORTEX_STEP_STATUS_WAITING",
                "WAITING",
            )
            if not is_waiting:
                continue
            abs_step_index = int(step.get("stepIndex", step_offset + idx))
            interaction_body: Dict[str, Any] = {"confirm": True}
            if "runCommand" in step:
                cmd = step["runCommand"].get("commandLine") or step["runCommand"].get("command") or ""
                interaction_body = {
                    "runCommand": {
                        "confirm": True,
                        "proposedCommandLine": cmd,
                        "submittedCommandLine": cmd,
                    }
                }
            elif "FilePermission" in str(step) or "filePermission" in step:
                interaction_body = {
                    "filePermission": {
                        "allow": True,
                        "scope": 2,
                    }
                }
            try:
                await self.call_unary(
                    "HandleCascadeUserInteraction",
                    {
                        "cascadeId": cascade_id,
                        "interaction": {
                            "trajectoryId": cascade_id,
                            "stepIndex": abs_step_index,
                            **interaction_body,
                        },
                    },
                    timeout=5.0,
                )
                approved += 1
            except Exception:
                pass
        return approved

    @staticmethod
    def extract_planner_response_text(steps: List[Dict[str, Any]]) -> Tuple[str, bool]:
        """Extract assistant response text and completion status from trajectory steps."""
        collected: List[str] = []
        any_running = False

        for step in steps:
            if not isinstance(step, dict):
                continue
            status = step.get("status")
            if status in (
                1,
                2,
                3,
                9,
                "CORTEX_STEP_STATUS_RUNNING",
                "CORTEX_STEP_STATUS_PENDING",
                "CORTEX_STEP_STATUS_WAITING",
                "RUNNING",
                "PENDING",
                "WAITING",
            ):
                any_running = True

            planner_resp = (
                step.get("plannerResponse")
                or step.get("assistantResponse")
                or step.get("chatResponse")
            )
            if isinstance(planner_resp, dict):
                text = (
                    planner_resp.get("response")
                    or planner_resp.get("modifiedResponse")
                    or planner_resp.get("text")
                    or planner_resp.get("content")
                    or ""
                )
                if text:
                    collected.append(str(text))
            elif isinstance(step.get("content"), str) and step.get("type") in (
                "PLANNER_RESPONSE",
                "ASSISTANT",
            ):
                collected.append(step["content"])

        full_text = "\n\n".join(part for part in collected if part.strip()).strip()
        is_complete = bool(full_text) and not any_running
        return full_text, is_complete

    async def stream_response_deltas(
        self,
        cascade_id: str,
        baseline_step_count: int,
        *,
        timeout: float = 120.0,
    ) -> AsyncGenerator[str, None]:
        """Yield live text deltas as `language_server.exe` generates the response."""
        deadline = time.monotonic() + timeout
        emitted_len = 0
        idle_ticks_with_text = 0

        while time.monotonic() < deadline:
            steps = await self.get_trajectory_steps(
                cascade_id, step_offset=baseline_step_count
            )
            if steps:
                await self.auto_approve_waiting_steps(
                    cascade_id, steps, step_offset=baseline_step_count
                )
                text, is_complete = self.extract_planner_response_text(steps)
                if len(text) > emitted_len:
                    delta = text[emitted_len:]
                    emitted_len = len(text)
                    idle_ticks_with_text = 0
                    yield delta
                elif is_complete and emitted_len > 0:
                    idle_ticks_with_text += 1
                    if idle_ticks_with_text >= 2:
                        break
            await asyncio.sleep(0.12)
