    async def get_available_models(self) -> List[Dict[str, Any]]:
        """Query `GetCascadeModelConfigData` and build the live model ID -> enum mapping."""
        resp: Dict[str, Any] = {}
        try:
            resp = await self.call_unary(
                "GetCascadeModelConfigData",
                {"metadata": self._metadata_payload()},
                timeout=10.0,
            )
        except Exception:
            try:
                resp = await self.call_unary(
                    "GetAvailableModels",
                    {"metadata": self._metadata_payload()},
                    timeout=10.0,
                )
            except Exception:
                resp = {}

        models_raw = (
            resp.get("clientModelConfigs")
            or resp.get("models")
            or resp.get("availableModels")
            or []
        )
        catalog: List[Dict[str, Any]] = []
        if isinstance(models_raw, list):
            for item in models_raw:
                if not isinstance(item, dict):
                    continue
                label = str(
                    item.get("label")
                    or item.get("displayName")
                    or item.get("modelName")
                    or ""
                )
                model_enum = (
                    item.get("model")
                    or item.get("modelOrAlias", {}).get("model")
                    or item.get("modelUid")
                )
                explicit_id = str(item.get("modelId") or "").strip().lower()
                norm_id = explicit_id or re.sub(
                    r"[^a-z0-9._-]+", "-", label.lower()
                ).strip("-")
                if norm_id and model_enum is not None:
                    self._dynamic_model_map[norm_id] = model_enum
                    if label:
                        self._dynamic_model_map[label.lower()] = model_enum
                        slug_label = re.sub(
                            r"[^a-z0-9._-]+", "-", label.lower()
                        ).strip("-")
                        self._dynamic_model_map[slug_label] = model_enum
                if norm_id:
                    catalog.append(
                        {
                            "id": norm_id,
                            "object": "model",
                            "owned_by": "antigravity",
                            "native_name": label or STATIC_MODEL_LABELS.get(norm_id, norm_id),
                            "model_enum": model_enum,
                            "quota_info": item.get("quotaInfo") or {},
                        }
                    )

        if not catalog:
            for row in STATIC_MODEL_CATALOG:
                catalog.append(
                    {
                        "id": row["id"],
                        "object": "model",
                        "owned_by": "antigravity",
                        "native_name": row["label"],
                        "model_enum": row["enum"],
                    }
                )
        self._available_models_cache = catalog
        return catalog

    def resolve_canonical_model_id(
        self,
        model_name: Optional[str],
        *,
        reasoning_effort: Optional[str] = None,
    ) -> Tuple[str, str]:
        """Return `(canonical_model_id, native_label)` strictly from the 9 real Antigravity v2.24.0 models."""
        raw = (model_name or "").strip().lower()
        effort = (reasoning_effort or "").strip().lower()

        if not raw or raw in {"antigravity", "default", "native"}:
            if effort == "high":
                cid = "gemini-4-argon-high"
            elif effort == "low":
                cid = "gemini-4-argon-low"
            else:
                cid = "gemini-4-argon-medium"
            return cid, STATIC_MODEL_LABELS[cid]

        if raw in MODEL_ALIASES:
            cid = MODEL_ALIASES[raw]
            if effort in {"high", "medium", "low"} and cid.startswith("gemini-4-argon-"):
                cid = f"gemini-4-argon-{effort}"
            elif effort in {"high", "medium", "low"} and cid.startswith("gemini-3.8-flash-"):
                cid = f"gemini-3.8-flash-{effort}"
            return cid, STATIC_MODEL_LABELS.get(cid, cid)

        if raw in STATIC_MODEL_ENUMS:
            return raw, STATIC_MODEL_LABELS.get(raw, raw)

        # Match by UI label (e.g. "Gemini 4 Argon (High)")
        for row in STATIC_MODEL_CATALOG:
            if raw == row["label"].lower():
                return row["id"], row["label"]

        # Partial match against the 9 real models
        if "opus" in raw:
            return "claude-opus-4-6-thinking", STATIC_MODEL_LABELS["claude-opus-4-6-thinking"]
        if "sonnet" in raw or "claude" in raw:
            return "claude-sonnet-4-6", STATIC_MODEL_LABELS["claude-sonnet-4-6"]
        if "gpt" in raw or "120b" in raw:
            return "gpt-oss-120b-medium", STATIC_MODEL_LABELS["gpt-oss-120b-medium"]
        if "flash" in raw:
            tier = effort if effort in {"high", "medium", "low"} else ("high" if "high" in raw else ("low" if "low" in raw else "medium"))
            cid = f"gemini-3.8-flash-{tier}"
            return cid, STATIC_MODEL_LABELS[cid]
        if "argon" in raw or "gemini" in raw or "pro" in raw:
            tier = effort if effort in {"high", "medium", "low"} else ("high" if "high" in raw else ("low" if "low" in raw else "medium"))
            cid = f"gemini-4-argon-{tier}"
            return cid, STATIC_MODEL_LABELS[cid]

        return "gemini-4-argon-medium", STATIC_MODEL_LABELS["gemini-4-argon-medium"]

    async def resolve_requested_model(
        self,
        model_name: Optional[str],
        *,
        reasoning_effort: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Resolve an OpenAI/Hermes model string into `{"model": <enum>}` for `cascadeConfig`."""
        if not self._dynamic_model_map:
            try:
                await self.get_available_models()
            except Exception:
                pass

        canonical_id, native_label = self.resolve_canonical_model_id(
            model_name, reasoning_effort=reasoning_effort
        )
        if canonical_id in self._dynamic_model_map:
            return {"model": self._dynamic_model_map[canonical_id]}
        if native_label.lower() in self._dynamic_model_map:
            return {"model": self._dynamic_model_map[native_label.lower()]}
        return {"model": STATIC_MODEL_ENUMS[canonical_id]}

