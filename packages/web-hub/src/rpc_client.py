class DirectConnectRPCClient:
    """Async ConnectRPC client talking to the isolated API profile's `language_server.exe`."""

    def __init__(
        self,
        *,
        port: Optional[int] = None,
        csrf_token: Optional[str] = None,
        profile_home: Optional[Path] = None,
        ide_version: str = "2.24.0",
    ) -> None:
        self.port = port or (
            int(os.environ["ANTIGRAVITY_API_RPC_PORT"])
            if os.environ.get("ANTIGRAVITY_API_RPC_PORT")
            else None
        )
        self.csrf_token = csrf_token or os.environ.get("ANTIGRAVITY_API_CSRF_TOKEN")
        from src.api_profile import resolve_api_profile_home

        self.profile_home = resolve_api_profile_home(profile_home)
        self.ide_version = ide_version
        self._dynamic_model_map: Dict[str, Any] = {}
        self._available_models_cache: List[Dict[str, Any]] = []
        self._experiments_cache: Optional[Dict[str, Any]] = None
        self._discovery_lock = asyncio.Lock()
        self._last_verified_at: float = 0.0
        self._ssl_ctx = ssl.create_default_context()
        self._ssl_ctx.check_hostname = False
        self._ssl_ctx.verify_mode = ssl.CERT_NONE

    @property
    def base_url(self) -> str:
        if not self.port:
            raise ConnectionError("ConnectRPC port is not yet discovered.")
        url = f"https://127.0.0.1:{self.port}"
        verify_loopback_rpc_url(url)
        return url

    def _headers(self, *, streaming: bool = False) -> Dict[str, str]:
        return {
            "Connect-Protocol-Version": "1",
            "Content-Type": (
                "application/connect+json" if streaming else "application/json"
            ),
            "x-codeium-csrf-token": self.csrf_token or "",
            "Origin": f"https://127.0.0.1:{self.port}",
        }

    def _metadata_payload(self) -> Dict[str, Any]:
        """Return 1:1 UI metadata block (`SKILL.md` Section 4 & `main_root.formatted.js`)."""
        return {
            "ideName": "antigravity",
            "ideVersion": self.ide_version,
            "extensionName": "antigravity",
            "extensionVersion": self.ide_version,
            "locale": "en",
        }

    def _is_rpc_token_expired(self) -> bool:
        """Return True if `rpc_connection.json` indicates the current OAuth access token is expired."""
        state_file = (
            self.profile_home
            / ".gemini/antigravity-api/scratch/rpc_connection.json"
        )
        if not state_file.is_file():
            return False
        try:
            data = json.loads(state_file.read_text(encoding="utf-8"))
            saved_exp = data.get("token_expires_at")
            if isinstance(saved_exp, (int, float)) and time.time() >= float(saved_exp) - 120:
                return True
        except Exception:
            pass
        return False

    async def ensure_connected(self) -> Tuple[int, str]:
        """Discover or verify the running `language_server` of the isolated API profile."""
        async with self._discovery_lock:
            if self._is_rpc_token_expired():
                self.port = None
                self.csrf_token = None
                from src.api_profile import APIProfileRuntime

                runtime = APIProfileRuntime(profile="api")
                await asyncio.to_thread(runtime.ensure_rpc_ready)

            if self.port and self.csrf_token:
                now = time.monotonic()
                if now - self._last_verified_at < 30.0:
                    return self.port, self.csrf_token
                if await self._probe_port(self.port, self.csrf_token):
                    self._last_verified_at = now
                    return self.port, self.csrf_token

            discovered = await asyncio.to_thread(self._discover_api_language_server)
            if discovered:
                self.port, self.csrf_token = discovered
                self._last_verified_at = time.monotonic()
                return self.port, self.csrf_token

            # If the API profile isn't started yet, start it via APIProfileRuntime
            from src.api_profile import APIProfileRuntime

            runtime = APIProfileRuntime(profile="api")
            await asyncio.to_thread(runtime.ensure_rpc_ready)
            discovered = await asyncio.to_thread(self._discover_api_language_server)
            if not discovered:
                raise ConnectionError(
                    "Could not discover ConnectRPC port/CSRF token for the isolated API profile language_server."
                )
            self.port, self.csrf_token = discovered
            self._last_verified_at = time.monotonic()
            return self.port, self.csrf_token

    def _discover_api_language_server(self) -> Optional[Tuple[int, str]]:
        """Locate the `language_server` process belonging specifically to the `api` profile."""
        state_file = (
            self.profile_home
            / ".gemini/antigravity-api/scratch/rpc_connection.json"
        )
        if state_file.is_file():
            try:
                data = json.loads(state_file.read_text(encoding="utf-8"))
                saved_exp = data.get("token_expires_at")
                if isinstance(saved_exp, (int, float)) and time.time() >= float(saved_exp) - 120:
                    return None
                port = int(data.get("port") or 0)
                token = str(data.get("csrf_token") or "")
                if port > 0 and token and self._probe_port_sync(port, token):
                    return port, token
            except Exception:
                pass

        from src.config import is_windows_os

        if is_windows_os():
            profile_marker = str(self.profile_home).replace("\\", "\\\\")
            ps_script = rf"""
$procs = @(Get-CimInstance Win32_Process | Where-Object {{ $_.Name -like 'language_server*' }})
foreach ($p in $procs) {{
    $cmd = [string]$p.CommandLine
    $exe = [string]$p.ExecutablePath
    if ($cmd -match '--csrf_token[\s=]+([A-Za-z0-9_-]+)') {{
        $token = $Matches[1]
        $conns = @(Get-NetTCPConnection -OwningProcess $p.ProcessId -State Listen -ErrorAction SilentlyContinue | Where-Object {{ $_.LocalAddress -eq '127.0.0.1' }} | Sort-Object LocalPort -Descending)
        $ports = ($conns | Select-Object -ExpandProperty LocalPort) -join ','
        Write-Output "$($p.ProcessId)|$token|$ports|$cmd"
    }}
}}
"""
            try:
                res = subprocess.run(
                    ["powershell.exe", "-NoProfile", "-Command", ps_script],
                    capture_output=True,
                    text=True,
                    timeout=5,
                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
                )
                candidates: List[Tuple[bool, str, List[int]]] = []
                for line in (res.stdout or "").splitlines():
                    parts = line.strip().split("|", 3)
                    if len(parts) < 4:
                        continue
                    _, token, ports_str, cmd = parts
                    ports = [
                        int(p) for p in ports_str.split(",") if p.strip().isdigit()
                    ]
                    is_api_profile = (
                        "antigravityapiprofile" in cmd.lower()
                        or "antigravity-api" in cmd.lower()
                    )
                    candidates.append((is_api_profile, token, ports))

                # Strictly prefer the isolated API profile process
                candidates.sort(key=lambda item: (not item[0]))
                for is_api, token, ports in candidates:
                    if not is_api and any(c[0] for c in candidates):
                        continue
                    for p in ports:
                        if self._probe_port_sync(p, token):
                            return p, token
            except Exception:
                pass
        else:
            # Linux / Container / Dokploy discovery via psutil + ps fallback
            try:
                import psutil

                posix_candidates: List[Tuple[bool, str, List[int]]] = []
                profile_str = str(self.profile_home).lower()
                for proc in psutil.process_iter(["pid", "name", "cmdline"]):
                    try:
                        cmdline_list = proc.info.get("cmdline") or []
                        name = str(proc.info.get("name") or "")
                        cmdline = " ".join(str(part) for part in cmdline_list)
                        if "language_server" not in name and "language_server" not in cmdline:
                            continue
                        m_tok = re.search(r"--csrf_token[=\s]+([A-Za-z0-9_-]+)", cmdline)
                        if not m_tok:
                            continue
                        token = m_tok.group(1)
                        ports: List[int] = []
                        m_port = re.search(r"--https_server_port[=\s]+(\d+)", cmdline)
                        if m_port:
                            ports.append(int(m_port.group(1)))
                        try:
                            for conn in proc.net_connections(kind="tcp"):
                                if conn.status == psutil.CONN_LISTEN and conn.laddr:
                                    p_num = int(conn.laddr.port)
                                    if p_num not in ports:
                                        ports.append(p_num)
                        except Exception:
                            pass
                        cmd_lower = cmdline.lower()
                        is_api_profile = (
                            profile_str in cmd_lower
                            or "antigravityapiprofile" in cmd_lower
                            or "antigravity-api" in cmd_lower
                        )
                        if ports:
                            posix_candidates.append((is_api_profile, token, ports))
                    except (psutil.Error, OSError, ValueError):
                        continue

                posix_candidates.sort(key=lambda item: (not item[0]))
                for is_api, token, ports in posix_candidates:
                    if not is_api and any(c[0] for c in posix_candidates):
                        continue
                    for p in ports:
                        if self._probe_port_sync(p, token):
                            return p, token
            except Exception:
                pass

            try:
                out = subprocess.check_output(["ps", "-eo", "pid,args"], text=True)
                for line in out.splitlines():
                    if "language_server" not in line:
                        continue
                    m_tok = re.search(r"--csrf_token[=\s]+([A-Za-z0-9_-]+)", line)
                    m_port = re.search(r"--https_server_port[=\s]+(\d+)", line)
                    if m_tok and m_port:
                        p, tok = int(m_port.group(1)), m_tok.group(1)
                        if self._probe_port_sync(p, tok):
                            return p, tok
            except Exception:
                pass
        return None

    @staticmethod
    def _probe_port_sync(port: int, csrf_token: str) -> bool:
        url = f"https://127.0.0.1:{port}{SERVICE_PREFIX}/GetStatus"
        verify_loopback_rpc_url(url)
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        req = urllib.request.Request(
            url,
            data=b"{}",
            headers={
                "Connect-Protocol-Version": "1",
                "Content-Type": "application/json",
                "x-codeium-csrf-token": csrf_token,
            },
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, context=ctx, timeout=1.5) as resp:
                return resp.status == 200
        except Exception:
            return False

    async def _probe_port(self, port: int, csrf_token: str) -> bool:
        return await asyncio.to_thread(self._probe_port_sync, port, csrf_token)

    def _unary_sync(
        self, method: str, payload: Dict[str, Any], timeout: float = 30.0
    ) -> Dict[str, Any]:
        url = f"{self.base_url}{SERVICE_PREFIX}/{method}"
        verify_loopback_rpc_url(url)
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(
            url, data=body, headers=self._headers(streaming=False), method="POST"
        )
        with urllib.request.urlopen(req, context=self._ssl_ctx, timeout=timeout) as resp:
            raw = resp.read().decode("utf-8", errors="replace")
            return json.loads(raw) if raw.strip() else {}

    async def call_unary(
        self, method: str, payload: Optional[Dict[str, Any]] = None, timeout: float = 30.0
    ) -> Dict[str, Any]:
        """Invoke a unary ConnectRPC method on the local `language_server.exe`."""
        await self.ensure_connected()
        try:
            return await asyncio.to_thread(
                self._unary_sync, method, payload or {}, timeout
            )
        except Exception:
            # Force re-discovery once on transient socket error
            self.port = None
            await self.ensure_connected()
            return await asyncio.to_thread(
                self._unary_sync, method, payload or {}, timeout
            )

