    async def start_cascade(
        self,
        workspace_dir: Path,
        *,
        model: Optional[str] = None,
    ) -> str:
        """Clone `uRa` (`main_root.formatted.js:80423`) to create a new `cascadeId`."""
        ws_uri = workspace_dir.resolve().as_uri()
        cascade_config = await self.build_ui_cascade_config(model)
        payload: Dict[str, Any] = {
            "metadata": self._metadata_payload(),
            "source": 1,  # CORTEX_TRAJECTORY_SOURCE_CASCADE_CLIENT
            "workspaceUris": [ws_uri],
            "overrideWorkspaceUris": [],
            "customAgentSpec": {"cascadeConfig": cascade_config},
        }
        resp = await self.call_unary("StartCascade", payload, timeout=15.0)
        cascade_id = str(resp.get("cascadeId") or "").strip()
        if not cascade_id:
            raise RuntimeError(f"StartCascade did not return a cascadeId: {resp}")
        return cascade_id

    async def send_user_cascade_message(
        self,
        cascade_id: str,
        text: str,
        workspace_dir: Path,
        *,
        model: Optional[str] = None,
        reasoning_effort: Optional[str] = None,
        blocking: bool = False,
        media: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Clone `M0` (`main_root.formatted.js:81556`) to send a user prompt with `messageOrigin: 1`.

        When images are passed (`media`), they are attached via the official Protobuf field
        `SendUserCascadeMessageRequest.media` (`repeated Media`, field 14 in `language_server.proto`
        with `mimeType`, `inlineData`, `description`) — identical to pasting an image in the IDE.
        """
        cascade_config = await self.build_ui_cascade_config(
            model, reasoning_effort=reasoning_effort
        )
        active_file_uri = (workspace_dir.resolve() / "src" / "main.py").as_uri()
        payload: Dict[str, Any] = {
            "metadata": self._metadata_payload(),
            "cascadeId": cascade_id,
            "items": [{"text": text}],
            "cascadeConfig": cascade_config,
            "clientType": 1,
            "messageOrigin": 1,  # AGENT_MESSAGE_ORIGIN_IDE (Shield 5)
            "editorState": {
                "activeDocumentUri": active_file_uri,
            },
            "blocking": bool(blocking),
        }
        if media:
            payload["media"] = media
        return await self.call_unary("SendUserCascadeMessage", payload, timeout=30.0)

