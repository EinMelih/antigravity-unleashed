def _json_document(value: Mapping[str, Any]) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def _redact(text: str, repo_root: Path) -> str:
    candidates = {
        str(repo_root.resolve()),
        repo_root.resolve().as_posix(),
        str(Path.home().resolve()),
        Path.home().resolve().as_posix(),
    }
    for candidate in sorted((item for item in candidates if item), key=len, reverse=True):
        text = re.sub(re.escape(candidate), "<REDACTED_PATH>", text, flags=re.IGNORECASE)
    text = re.sub(r"(?i)\b[A-Z]:[\\/](?:[^\s|`\"'<>]+[\\/]?)+", "<REDACTED_PATH>", text)
    for pattern in SECRET_PATTERNS:
        if pattern.pattern.startswith("(?i)(https?://)"):
            text = pattern.sub(r"\1[REDACTED]@", text)
        else:
            text = pattern.sub("[REDACTED]", text)
    return text


def build_bundle(repo_root: Path) -> dict[str, str]:
    routes = collect_http_routes(repo_root)
    schema = collect_database_schema(repo_root)
    graph = collect_import_graph(repo_root)
    frontend_graph = collect_frontend_import_graph(repo_root)
    dependencies = collect_package_dependencies(repo_root)
    raw = {
        "DEPENDENCY_INVENTORY.md": render_dependencies_markdown(dependencies),
        "FRONTEND_IMPORT_GRAPH.md": render_frontend_import_graph_markdown(frontend_graph),
        "HTTP_ROUTES.md": render_routes_markdown(routes),
        "PYTHON_IMPORT_GRAPH.md": render_import_graph_markdown(graph),
        "SQLITE_SCHEMA.md": render_schema_markdown(schema),
        "database_schema.json": _json_document(schema),
        "dependencies.json": _json_document(dependencies),
        "frontend_import_graph.json": _json_document(frontend_graph),
        "http_routes.json": _json_document(routes),
        "python_import_graph.json": _json_document(graph),
    }
    return {name: _redact(content, repo_root) for name, content in sorted(raw.items())}


def write_bundle(output_dir: Path, bundle: Mapping[str, str]) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in sorted(bundle.items()):
        with (output_dir / name).open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)


def check_bundle(output_dir: Path, bundle: Mapping[str, str]) -> list[str]:
    drift: list[str] = []
    for name, expected in sorted(bundle.items()):
        path = output_dir / name
        if not path.is_file():
            drift.append(f"missing: {name}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            drift.append(f"changed: {name}")
    return drift


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=default_root)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Return non-zero when generated references differ; do not write files.",
    )
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    args = parse_args(argv)
    repo_root = args.repo_root.resolve()
    output_dir = (
        args.output_dir.resolve() if args.output_dir else repo_root / "docs" / "generated"
    )
    bundle = build_bundle(repo_root)
    if args.check:
        drift = check_bundle(output_dir, bundle)
        if drift:
            print("Reference documentation drift detected:")
            for item in drift:
                print(f"- {item}")
            print("Run: python scripts/generate_reference_docs.py")
            return 1
        print(f"Reference documentation is current ({len(bundle)} files).")
        return 0
    write_bundle(output_dir, bundle)
    print(f"Generated {len(bundle)} reference files in {output_dir}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
