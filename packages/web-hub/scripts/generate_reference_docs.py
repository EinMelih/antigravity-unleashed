#!/usr/bin/env python3
"""Generate deterministic, source-derived reference appendices.

The generator deliberately separates structural facts from hand-written guidance:

* HTTP registrations are discovered statically from Python source.
* SQLite metadata comes from an empty, temporary database initialized by the
  current application code.
* Python dependencies are extracted statically from imports.
* Direct and locked package dependencies come from repository manifests.

No live database rows, configuration values, credentials, timestamps, or
machine-specific absolute paths are included in the output.
"""

