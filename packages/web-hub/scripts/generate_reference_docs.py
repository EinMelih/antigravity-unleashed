def _relative_source(path: Path, repo_root: Path) -> str:
    return path.resolve().relative_to(repo_root.resolve()).as_posix()


def _python_sources(repo_root: Path) -> list[Path]:
    sources = list((repo_root / "src").rglob("*.py"))
    sources.extend(repo_root / name for name in ROOT_ENTRYPOINTS if (repo_root / name).is_file())
    return sorted(sources, key=lambda path: _relative_source(path, repo_root))


def _expr_text(node: ast.AST | None) -> str:
    if node is None:
        return ""
    try:
        return ast.unparse(node)
    except (AttributeError, ValueError):
        return node.__class__.__name__


def _attribute_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        parent = _attribute_name(node.value)
        return f"{parent}.{node.attr}" if parent else node.attr
    return None


class _Symbol(str):
    """A source expression that was not resolved to a literal value."""


def _static_value(node: ast.AST, environment: Mapping[str, Any]) -> Any:
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Name):
        return environment.get(node.id, _Symbol(node.id))
    if isinstance(node, ast.Attribute):
        return _Symbol(_attribute_name(node) or _expr_text(node))
    if isinstance(node, ast.Tuple):
        return tuple(_static_value(element, environment) for element in node.elts)
    if isinstance(node, (ast.List, ast.Set)):
        return [_static_value(element, environment) for element in node.elts]
    if isinstance(node, ast.Dict):
        result: dict[Any, Any] = {}
        for key, value in zip(node.keys, node.values):
            if key is None:
                continue
            static_key = _static_value(key, environment)
            try:
                hash(static_key)
            except TypeError:
                static_key = _Symbol(_expr_text(key))
            result[static_key] = _static_value(value, environment)
        return result
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left = _static_value(node.left, environment)
        right = _static_value(node.right, environment)
        if type(left) is str and type(right) is str:
            return left + right
    if isinstance(node, ast.JoinedStr):
        pieces: list[str] = []
        for value in node.values:
            if not isinstance(value, ast.Constant) or not isinstance(value.value, str):
                return _Symbol(_expr_text(node))
            pieces.append(value.value)
        return "".join(pieces)
    return _Symbol(_expr_text(node))


def _bind_target(target: ast.AST, value: Any, environment: dict[str, Any]) -> None:
    if isinstance(target, ast.Name):
        environment[target.id] = value
        return
    if isinstance(target, (ast.List, ast.Tuple)) and isinstance(value, Sequence):
        for child, item in zip(target.elts, value):
            _bind_target(child, item, environment)


class _RouteVisitor(ast.NodeVisitor):
    def __init__(self, source: str) -> None:
        self.source = source
        self.environment: dict[str, Any] = {}
        self.routes: list[dict[str, Any]] = []
        self.unresolved: list[dict[str, Any]] = []

    def _record(
        self,
        node: ast.Call,
        method_node: ast.AST | None,
        path_node: ast.AST | None,
        handler_node: ast.AST | None,
        fixed_method: str | None = None,
        fixed_handler: str | None = None,
    ) -> None:
        method_value = fixed_method or (
            _static_value(method_node, self.environment) if method_node is not None else None
        )
        path_value = (
            _static_value(path_node, self.environment) if path_node is not None else None
        )
        handler_value = fixed_handler or (
            _static_value(handler_node, self.environment) if handler_node is not None else ""
        )
        if type(method_value) is str and type(path_value) is str:
            self.routes.append(
                {
                    "handler": str(handler_value),
                    "line": node.lineno,
                    "method": method_value.upper(),
                    "path": path_value,
                    "source": self.source,
                }
            )
            return
        self.unresolved.append(
            {
                "expression": _expr_text(node),
                "line": node.lineno,
                "source": self.source,
            }
        )

    def visit_Assign(self, node: ast.Assign) -> None:  # noqa: N802
        value = _static_value(node.value, self.environment)
        for target in node.targets:
            _bind_target(target, value, self.environment)
        self.visit(node.value)

    def visit_AnnAssign(self, node: ast.AnnAssign) -> None:  # noqa: N802
        if node.value is not None:
            _bind_target(node.target, _static_value(node.value, self.environment), self.environment)
            self.visit(node.value)

    def visit_For(self, node: ast.For) -> None:  # noqa: N802
        values = _static_value(node.iter, self.environment)
        original = self.environment
        if isinstance(values, (list, tuple)):
            for value in values:
                self.environment = dict(original)
                _bind_target(node.target, value, self.environment)
                for statement in node.body:
                    self.visit(statement)
        else:
            self.environment = dict(original)
            _bind_target(node.target, _Symbol(_expr_text(node.target)), self.environment)
            for statement in node.body:
                self.visit(statement)
        self.environment = original
        for statement in node.orelse:
            self.visit(statement)

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:  # noqa: N802
        self._visit_function(node)

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> None:  # noqa: N802
        self._visit_function(node)

    def _visit_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> None:
        for decorator in node.decorator_list:
            if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                continue
            method = WEB_ROUTE_METHODS.get(decorator.func.attr.lower())
            registrar = (_attribute_name(decorator.func.value) or "").lower()
            if method and "route" in registrar and decorator.args:
                self._record(
                    decorator,
                    None,
                    decorator.args[0],
                    None,
                    fixed_method=method,
                    fixed_handler=node.name,
                )
        original = self.environment
        self.environment = dict(original)
        for statement in node.body:
            self.visit(statement)
        self.environment = original

    def visit_If(self, node: ast.If) -> None:  # noqa: N802
        original = self.environment
        for branch in (node.body, node.orelse):
            self.environment = dict(original)
            for statement in branch:
                self.visit(statement)
        self.environment = original

    def visit_Call(self, node: ast.Call) -> None:  # noqa: N802
        function = node.func
        if isinstance(function, ast.Attribute):
            registrar = function.attr
            if registrar in METHOD_BY_REGISTRAR and node.args:
                handler = node.args[1] if len(node.args) > 1 else None
                self._record(
                    node,
                    None,
                    node.args[0],
                    handler,
                    fixed_method=METHOD_BY_REGISTRAR[registrar],
                )
            elif registrar == "add_route" and len(node.args) >= 2:
                handler = node.args[2] if len(node.args) > 2 else None
                self._record(node, node.args[0], node.args[1], handler)
            else:
                owner = (_attribute_name(function.value) or "").lower()
                method = WEB_ROUTE_METHODS.get(registrar.lower())
                if owner == "web" and method and node.args:
                    handler = node.args[1] if len(node.args) > 1 else None
                    self._record(node, None, node.args[0], handler, fixed_method=method)
                elif owner == "web" and registrar.lower() == "route" and len(node.args) >= 2:
                    handler = node.args[2] if len(node.args) > 2 else None
                    self._record(node, node.args[0], node.args[1], handler)
        self.generic_visit(node)


def collect_http_routes(repo_root: Path) -> dict[str, Any]:
    routes: list[dict[str, Any]] = []
    unresolved: list[dict[str, Any]] = []
    parse_errors: list[dict[str, Any]] = []
    for path in _python_sources(repo_root):
        source = _relative_source(path, repo_root)
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=source)
        except (OSError, SyntaxError, UnicodeDecodeError) as error:
            parse_errors.append({"error": str(error), "source": source})
            continue
        visitor = _RouteVisitor(source)
        visitor.visit(tree)
        routes.extend(visitor.routes)
        unresolved.extend(visitor.unresolved)

    unique_routes = {
        (item["method"], item["path"], item["handler"], item["source"], item["line"]): item
        for item in routes
    }
    unique_unresolved = {
        (item["source"], item["line"], item["expression"]): item for item in unresolved
    }
    return {
        "format_version": 1,
        "parse_errors": sorted(parse_errors, key=lambda item: (item["source"], item["error"])),
        "routes": sorted(
            unique_routes.values(),
            key=lambda item: (
                item["path"],
                item["method"],
                item["source"],
                item["line"],
                item["handler"],
            ),
        ),
        "source": "static Python AST analysis",
        "unresolved_registrations": sorted(
            unique_unresolved.values(),
            key=lambda item: (item["source"], item["line"], item["expression"]),
        ),
    }


